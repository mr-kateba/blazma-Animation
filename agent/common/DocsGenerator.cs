using System.Text;
using System.Text.Json.Nodes;

namespace Blazma.AgentTools;

/// <summary>Generates docs/MCP_TOOLS.md and docs/CLI_REFERENCE.md from the command registry.</summary>
public static class DocsGenerator
{
    const string Banner = "<!-- Generated by `blazma-anim docs`. Do not edit by hand: change the command descriptors instead. -->\n\n";

    static string Cell(string? s) => (s ?? "").Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ");

    static IEnumerable<(string Name, string Type, bool Required, string Description, string Constraints)> Args(JsonObject schema)
    {
        var required = (schema["required"] as JsonArray)?.Select(x => (string)x!).ToHashSet() ?? new HashSet<string>();
        foreach (var (name, node) in (JsonObject)(schema["properties"] ?? new JsonObject()))
        {
            var p = (JsonObject)node!;
            var c = new List<string>();
            if (p["minimum"] is { } min) c.Add($"min {min.ToJsonString()}");
            if (p["minLength"] is { } ml) c.Add($"min length {ml.ToJsonString()}");
            yield return (name, (string?)p["type"] ?? "any", required.Contains(name), (string?)p["description"] ?? "", string.Join(", ", c));
        }
    }

    static void ArgTable(StringBuilder sb, JsonObject schema)
    {
        var args = Args(schema).ToList();
        if (args.Count == 0) { sb.AppendLine("No arguments.\n"); return; }
        sb.AppendLine("| Argument | Type | Required | Description |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var a in args)
            sb.AppendLine($"| `{a.Name}` | {a.Type} | {(a.Required ? "yes" : "no")} | {Cell(a.Description)}{(a.Constraints.Length > 0 ? $" ({a.Constraints})" : "")} |");
        sb.AppendLine();
    }

    static string Anchor(string s) => s;

    public static string McpTools(IReadOnlyList<ToolInfo> commands)
    {
        var sb = new StringBuilder(Banner);
        sb.AppendLine("# MCP tools (`blazma-mcp`)\n");
        sb.AppendLine("The MCP server exposes one tool per registry command plus a few session tools. Tool names are the command id with `.` replaced by `_` (`key.set` becomes `key_set`). Each result is the `CommandResult` as pretty JSON text (`ok`, `data`, `transactionId`, `warnings`, `error`); when `ok` is false the tool result has `isError = true`.\n");
        sb.AppendLine("Effects: **readonly** runs immediately; **mutating** changes the project and can be undone; **destructive** needs the user's approval in the app (in headless mode it runs directly); **external** reads or writes files outside the project and needs approval unless the path is in an allowed folder.\n");
        sb.AppendLine("## Session tools\n");
        sb.AppendLine("| Tool | Where | Description |");
        sb.AppendLine("|---|---|---|");
        foreach (var t in SessionTools.All)
            sb.AppendLine($"| `{t.Name}` | {(t.HeadlessOnly ? "headless only" : "both")} | {Cell(t.Description)} |");
        sb.AppendLine();
        foreach (var t in SessionTools.All)
        {
            sb.AppendLine($"### `{t.Name}`\n");
            ArgTable(sb, t.Schema);
        }
        sb.AppendLine("## Command tools\n");
        sb.AppendLine("| Tool | Effect | Summary |");
        sb.AppendLine("|---|---|---|");
        foreach (var c in commands)
            sb.AppendLine($"| [`{c.ToolName}`](#{Anchor(c.ToolName)}) | {c.Effect} | {Cell(c.Summary)} |");
        sb.AppendLine();
        foreach (var c in commands)
        {
            sb.AppendLine($"### `{c.ToolName}`\n");
            sb.AppendLine($"{c.Summary}\n");
            sb.AppendLine($"Effect: **{c.Effect}**. Command id: `{c.Id}`.\n");
            ArgTable(sb, c.InputSchema);
        }
        return sb.ToString();
    }

    public static string CliReference(IReadOnlyList<ToolInfo> commands)
    {
        var sb = new StringBuilder(Banner);
        sb.AppendLine("# CLI reference (`blazma-anim`)\n");
        sb.AppendLine("```");
        sb.AppendLine("blazma-anim commands [--json]");
        sb.AppendLine("blazma-anim new <file.blazanim> [--name NAME] [--json]");
        sb.AppendLine("blazma-anim inspect <file> [--json]");
        sb.AppendLine("blazma-anim exec <file> <command-id> [--args '<json>'] [--arg key=value ...] [--no-save] [--json]");
        sb.AppendLine("blazma-anim run <file> <script.jsonl> [--no-save] [--json]");
        sb.AppendLine("blazma-anim docs <out-dir>");
        sb.AppendLine("```\n");
        sb.AppendLine("Every command except `new`, `commands` and `docs` also accepts `--attach` (omit the file argument) to drive the running Blazma Animation window instead of a file. `--pipe <name>` overrides the IPC pipe name (tests only).\n");
        sb.AppendLine("## Sub-commands\n");
        sb.AppendLine("| Sub-command | What it does |");
        sb.AppendLine("|---|---|");
        sb.AppendLine("| `commands` | Lists every command with its effect and arguments. |");
        sb.AppendLine("| `new` | Creates a project containing the default mannequin. Fails if the file exists. |");
        sb.AppendLine("| `inspect` | Same as `exec <file> project.inspect`. |");
        sb.AppendLine("| `exec` | Runs one command inside one task, then saves atomically (unless `--no-save`, a read-only command, or a failure). `--args` takes a JSON object; `--arg key=value` can repeat and is converted using the command's schema. |");
        sb.AppendLine("| `run` | Runs a JSON-lines script (one `{\"command\":\"key.set\",\"args\":{...}}` per line; blank lines and lines starting with `#` are skipped) in ONE task. Stops at the first failure without saving; otherwise saves once. Script variables: `${character}` (the project's first character) and `${clip}` (its last clip) are replaced inside string arguments; `\"save\":{\"name\":\"field\"}` on a line stores `data.field` of its result as `${name}` for later lines (e.g. `{\"command\":\"clip.create\",\"args\":{\"name\":\"Walk\"},\"save\":{\"clip\":\"clipId\"}}`). |");
        sb.AppendLine("| `docs` | Writes `MCP_TOOLS.md` and `CLI_REFERENCE.md` into the folder. |");
        sb.AppendLine();
        sb.AppendLine("## Output and exit codes\n");
        sb.AppendLine("Default output is human-readable text; `--json` prints machine-readable JSON on stdout (for `exec`: the `CommandResult`; for `run`: `{ok, steps:[...], saved}`). Errors go to stderr.\n");
        sb.AppendLine("| Code | Meaning |");
        sb.AppendLine("|---|---|");
        sb.AppendLine("| 0 | Success |");
        sb.AppendLine("| 1 | User or input error (bad arguments, file locked, command failed) |");
        sb.AppendLine("| 2 | Validation failure (reserved) |");
        sb.AppendLine("| 3 | Internal error |");
        sb.AppendLine("| 130 | Cancelled (Ctrl+C) |");
        sb.AppendLine();
        sb.AppendLine("## Commands\n");
        sb.AppendLine("Use as `blazma-anim exec <file> <id> --arg name=value ...`.\n");
        sb.AppendLine("| Command id | Effect | Arguments (`*` = required) | Summary |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var c in commands)
        {
            var args = string.Join(", ", Args(c.InputSchema).Select(a => $"`{a.Name}`{(a.Required ? "*" : "")}:{a.Type}"));
            sb.AppendLine($"| `{c.Id}` | {c.Effect} | {(args.Length == 0 ? "-" : args)} | {Cell(c.Summary)} |");
        }
        sb.AppendLine();
        sb.AppendLine("## Argument details\n");
        foreach (var c in commands)
        {
            sb.AppendLine($"### `{c.Id}`\n");
            sb.AppendLine($"{c.Summary} (effect: {c.Effect})\n");
            ArgTable(sb, c.InputSchema);
        }
        return sb.ToString();
    }
}
