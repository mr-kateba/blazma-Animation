    [Fact]
    public void Acceptance_Phase9_HurtboxesAutoGenerated_CoverTheBody()
    {
        var c = C9.Build();
        var s = c.S;
        var def = P8.Character(s, c.Defender);
        var rig = P8.RigOf(s, c.Defender);
        var boxes = def.Combat!.Hurtboxes;
        var names = boxes.Select(h => rig.FindBone(h.Bone)!.Name).ToHashSet();
        foreach (var n in new[] { "pelvis", "spine_01", "spine_03", "neck", "head", "upper_arm_l", "lower_arm_r", "hand_l", "thigh_r", "calf_l", "foot_r" })
            Assert.Contains(n, names);
        Assert.DoesNotContain("root", names);
        Assert.Equal(HitZone.High, boxes.Single(h => rig.FindBone(h.Bone)!.Name == "head").Zone);
        Assert.Equal(HitZone.Low, boxes.Single(h => rig.FindBone(h.Bone)!.Name == "calf_l").Zone);
        Assert.Equal(HitZone.Mid, boxes.Single(h => rig.FindBone(h.Bone)!.Name == "spine_03").Zone);

        // Each segment's capsule contains both of its joints (no gaps along the body), and radii follow body proportions.
        var rest = new RigEvaluator(rig).RestModel();
        foreach (var h in boxes)
        {
            var w = CombatEvaluator.HurtboxShape(rig, h, rest, Transform.Identity)!.Value;
            var joint = rest[rig.IndexOf(h.Bone)].Translation;
            Collision.ClosestPtSegmentSegment(joint, joint, w.A, w.B, out _, out var q);
            Assert.True((joint - q).Length() <= w.Radius + 1e-9, rig.FindBone(h.Bone)!.Name);
        }
        double R(string n) => boxes.Single(h => rig.FindBone(h.Bone)!.Name == n).Shape.Radius;
        Assert.True(R("spine_03") > R("thigh_l") && R("thigh_l") > R("lower_arm_l"));
        Assert.InRange(R("spine_03"), 0.12, 0.2);

        // Editable: shrink the head, disable a hand; radiusScale doubles everything.
        var head = boxes.Single(h => rig.FindBone(h.Bone)!.Name == "head").Id.ToString();
        P8.Ok(s, "hurtbox.update", new { characterId = c.Defender, hurtboxId = head, radius = 0.05, zone = "high" });
        Assert.Equal(0.05, P8.Character(s, c.Defender).Combat!.Hurtboxes.Single(h => h.Id.ToString() == head).Shape.Radius);
        var r1 = R("thigh_l");
        P8.Ok(s, "hurtbox.generate", new { characterId = c.Defender, radiusScale = 2.0 });
        Assert.Equal(2 * r1, P8.Character(s, c.Defender).Combat!.Hurtboxes.Single(h => rig.FindBone(h.Bone)!.Name == "thigh_l").Shape.Radius, 9);

        // An imported humanoid (CesiumMan) gets hurtboxes too (mapped segments).
        var (s2, _, ces) = P8.Scene();
        var gen = P8.Ok(s2, "hurtbox.generate", new { characterId = ces }).Data!;
        Assert.True((int)gen["count"]! >= 10);
    }

