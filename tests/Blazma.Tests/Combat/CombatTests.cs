    [Fact]
    public void Acceptance_Phase9_HitReaction_BendsAwayFromTheHit_AndRecovers()
    {
        var c = C9.Build();
        var s = c.S;
        var rig = P8.RigOf(s, c.Defender);
        var head = P8.Bone(rig, H.Head);
        var root = SequenceEvaluator.RootMotionBoneOf(rig);
        var restHead = new RigEvaluator(rig).RestModel()[head].Translation;
        foreach (var (from, push) in new[] { ("front", -Vec3.UnitZ), ("back", Vec3.UnitZ), ("left", -Vec3.UnitX), ("right", Vec3.UnitX) })
        {
            var d = P8.Ok(s, "reaction.generate", new { characterId = c.Defender, direction = from, height = "high", strength = 0.5, knockback = 0.3 }).Data!;
            var clip = P8.Clip(s, (string)d["clipId"]!);
            var peak = (long)d["peakFrame"]!;
            Assert.InRange((double)d["peakDegrees"]!, 21.5, 22.5 + 1e-9); // 10° + 25°·0.5 at the true peak; frames sample it
            var m = P8.Model(rig, clip, peak);
            var headMove = m[head].Translation - m[root].Translation - (restHead - new RigEvaluator(rig).RestModel()[root].Translation);
            Assert.True(Vec3.Dot(headMove, push) > 0.05, $"{from}: head moves {headMove}");
            Assert.True(Math.Abs(Vec3.Dot(headMove, Vec3.Cross(Vec3.UnitY, push))) < 0.01, $"{from}: sideways {headMove}");
            // Knockback along the push; the last frame is the base pose again apart from the travel.
            var last = P8.Model(rig, clip, clip.DurationFrames);
            Assert.True((last[root].Translation - (new RigEvaluator(rig).RestModel()[root].Translation + push * 0.3)).Length() < 1e-4, from);
            var rest = new RigEvaluator(rig).RestModel();
            for (var b = 0; b < rig.Bones.Count; b++)
                Assert.True((last[b].Translation - push * 0.3 - rest[b].Translation).Length() < 1e-3, $"{from}: bone {rig.Bones[b].Name} not back at the base pose");
        }

        // From a hit test: the reaction pushes the way the blade travelled (in the defender's frame), and is undoable.
        var hit = P8.Ok(s, "combat.hit_test", new { attackerCharacterId = c.Attacker, attackClipId = c.Attack, defenderCharacterId = c.Defender, defenderZ = 0.75 }).Data!;
        var args = hit["reactionArgs"]!.AsObject();
        var before = C9.State(s.Project);
        var gen = P8.Ok(s, "reaction.generate", JsonSerializer.Deserialize<Dictionary<string, object>>(args.ToJsonString())!);
        var rc = P8.Clip(s, (string)gen.Data!["clipId"]!);
        var pk = P8.Model(rig, rc, (long)gen.Data!["peakFrame"]!);
        var mv = pk[head].Translation - pk[root].Translation - (restHead - new RigEvaluator(rig).RestModel()[root].Translation);
        var dir = new Vec3((double)args["directionX"]!, 0, (double)args["directionZ"]!);
        Assert.True(Vec3.Dot(new Vec3(mv.X, 0, mv.Z).Normalized(), dir) > 0.9, $"{mv} vs {dir}");
        Assert.True(s.Undo(CommandOrigin.Test).Ok);
        Assert.Equal(before, C9.State(s.Project));

        // From a base clip frame: frame 0 of the reaction is that pose.
        var fromClip = P8.Ok(s, "reaction.generate", new { characterId = c.Attacker, baseClipId = c.Attack, baseFrame = 14, direction = "front" }).Data!;
        var b0 = P8.Model(rig, P8.Clip(s, (string)fromClip["clipId"]!), 0);
        var a14 = P8.Model(rig, P8.Clip(s, c.Attack), 14);
        for (var b = 0; b < b0.Length; b++) Assert.True((b0[b].Translation - a14[b].Translation).Length() < 1e-3, rig.Bones[b].Name);
    }

