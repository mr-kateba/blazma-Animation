            ("hurtbox.update", new { characterId = c.Defender, hurtboxId = hurt, enabled = false, radius = 0.3 }),
            ("hurtbox.remove", new { characterId = c.Defender, hurtboxId = hurt }),
            ("hurtbox.remove", new { characterId = c.Defender }),
            ("reaction.set_rule", new { characterId = c.Defender, ruleId = rule, name = "r2", height = "low" }),
            ("reaction.remove_rule", new { characterId = c.Defender, ruleId = rule }),
            ("reaction.generate", new { characterId = c.Defender, direction = "left" }),
            ("combo.create", new { characterId = c.Attacker, name = "D" }),
