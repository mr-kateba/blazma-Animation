    static double MaxAcc(Transform[][] m, int from, int to)
    {
        var best = 0.0;
        for (var f = Math.Max(1, from); f <= Math.Min(m.Length - 2, to); f++)
            for (var b = 0; b < m[f].Length; b++)
                best = Math.Max(best, (m[f + 1][b].Translation - m[f][b].Translation * 2 + m[f - 1][b].Translation).Length());
        return best;
    }

    [Fact]
    public void Acceptance_Phase9_ComboOfThree_WithCancelWindows_BakesContinuously()
    {
        var c = C9.Build();
        var s = c.S;
        var atk2 = P8.ApplyTemplate(s, "builtin.attack_swing", c.Attacker, 1.0);
        var combo = (string)P8.Ok(s, "combo.create", new { characterId = c.Attacker, name = "Triple" }).Data!["comboId"]!;
        P8.Ok(s, "combo.add_attack", new { comboId = combo, clipId = c.Attack, input = "X", cancelStartFrame = 20, cancelEndFrame = 28 });
        var second = (string)P8.Ok(s, "combo.add_attack", new { comboId = combo, clipId = atk2, input = "X", cancelStartFrame = 18, cancelEndFrame = 24, blendFrames = 4 }).Data!["attackId"]!;
        P8.Ok(s, "combo.add_attack", new { comboId = combo, clipId = c.Attack, input = "Y", blendFrames = 4 });
        P8.Ok(s, "combo.set_cancel_window", new { comboId = combo, attackId = second, linkFrame = 20 });
        Assert.Equal("invalid_args", P8.Err(P8.Run(s, "combo.set_cancel_window", new { comboId = combo, attackId = second, linkFrame = 26 }))); // outside the window

        var info = P8.Ok(s, "combo.inspect", new { comboId = combo }).Data!;
        var attacks = info["attacks"]!.AsArray();
        Assert.Equal(new long[] { 0, 20, 40 }, attacks.Select(a => (long)a!["startFrame"]!).ToArray());
        Assert.Equal(76, (long)info["lastFrame"]!); // the last attack (36 frames from 40) plays to its end
        Assert.Equal(20, (long)attacks[0]!["cancelWindow"]!["startFrame"]!);

        // Bake to a clip through the sequence machinery: no pose jump at the links, the root continues, hitboxes follow.
        var bake = P8.Ok(s, "combo.bake", new { comboId = combo, name = "Triple combo" }).Data!;
        var clip = P8.Clip(s, (string)bake["clipId"]!);
        var rig = P8.RigOf(s, c.Attacker);
        var m = Enumerable.Range(0, (int)clip.DurationFrames + 1).Select(f => P8.Model(rig, clip, f)).ToArray();
        var accLinks = Math.Max(MaxAcc(m, 18, 26), MaxAcc(m, 38, 46));
        var accAttack = Math.Max(MaxAcc(m, 2, 17), MaxAcc(m, 46, m.Length - 2));
        Assert.True(accLinks <= 1.2 * accAttack, $"links {accLinks:0.0000} vs attacks {accAttack:0.0000} m/frame²");
        double MaxStep(int from, int to) => Enumerable.Range(Math.Max(1, from), Math.Min(m.Length - 1, to) - Math.Max(1, from) + 1)
            .Max(f => Enumerable.Range(0, m[f].Length).Max(b => (m[f][b].Translation - m[f - 1][b].Translation).Length()));
        var stepLinks = Math.Max(MaxStep(19, 25), MaxStep(39, 45));
        var stepAttacks = Math.Max(MaxStep(1, 18), MaxStep(46, m.Length - 1));
        Assert.True(stepLinks <= 1.2 * stepAttacks, $"links move {stepLinks:0.000} m/frame vs attacks {stepAttacks:0.000}");
        Assert.Contains(clip.Markers, x => x.Time == Flicks.FromFrame(20, clip.Fps));
        Assert.Contains(clip.Markers, x => x.Time == Flicks.FromFrame(40, clip.Fps));
        // Attack 1's blade (active 10–18) and attack 3's (shifted to 50–58); attack 2 has no hitbox.
        var hb = clip.Combat!.Hitboxes;
        Assert.Equal(2, hb.Count);
        Assert.Equal((10L, 18L), CombatEvaluator.ActiveFrames(hb[0], clip.Fps).Single());
        Assert.Equal((50L, 58L), CombatEvaluator.ActiveFrames(hb[1], clip.Fps).Single());
        Assert.Contains(clip.Events, e => e.Name == "cancel_window" && e.Time == Flicks.FromFrame(20, clip.Fps) && e.Data["next"] == "X");

        // Bake to a sequence instead: an editable sequence with the same timing; undo removes it.
        var seq = P8.Ok(s, "combo.bake", new { comboId = combo, target = "sequence" }).Data!;
        var sq = s.Project.FindSequence(ObjectId.Parse((string)seq["sequenceId"]!))!;
        Assert.Equal(new long[] { 0, 20, 40 }, sq.Items.Select(i => i.StartFrame).ToArray());
        Assert.True(s.Undo(CommandOrigin.Test).Ok);
        Assert.Null(s.Project.FindSequence(sq.Id));
    }

