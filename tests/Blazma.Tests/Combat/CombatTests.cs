    /// <summary>Independent oracle: blade capsule from PropEvaluator (Phase 8 code), defender hurtbox capsules from the rest pose,
    /// distances by dense point sampling every 1/128 frame.</summary>
    internal static (double Time, string Bone) Oracle(C9.Scene c, Vec3 at, double facingDeg)
    {
        var s = c.S;
        var p = s.Project;
        var clip = P8.Clip(s, c.Attack);
        var rigA = P8.RigOf(s, c.Attacker);
        var rigD = P8.RigOf(s, c.Defender);
        var prop = p.FindProp(ObjectId.Parse(c.Sword))!;
        var place = new Transform(at, Quat.FromAxisAngle(Vec3.UnitY, facingDeg * Math.PI / 180), Vec3.One);
        var rest = new RigEvaluator(rigD).RestModel();
        var hurt = P8.Character(s, c.Defender).Combat!.Hurtboxes.Select(h =>
        {
            var m = place * rest[rigD.IndexOf(h.Bone)] * h.Offset;
            var half = m.Rotation.Rotate(Vec3.UnitY * (h.Shape.Length / 2));
            return (Name: rigD.FindBone(h.Bone)!.Name, A: m.Translation - half, B: m.Translation + half, h.Shape.Radius);
        }).ToList();
        static double PointSeg(Vec3 x, Vec3 a, Vec3 b)
        {
            var d = b - a;
            var u = Math.Clamp(Vec3.Dot(x - a, d) / d.LengthSquared(), 0, 1);
            return (a + d * u - x).Length();
        }
        for (var t = 10.0; t < 18; t += 1.0 / 128)
        {
            var w = PropEvaluator.WorldAt(p, prop, clip, rigA, CombatEvaluator.TimeOf(t, clip.Fps), P8.Character(s, c.Attacker).Id);
            var a = w.Translation - w.Rotation.Rotate(Vec3.UnitY * 0.4);
            var b = w.Translation + w.Rotation.Rotate(Vec3.UnitY * 0.4);
            (double Gap, string Name)? best = null;
            for (var i = 0; i <= 160; i++)
            {
                var x = Vec3.Lerp(a, b, i / 160.0);
                foreach (var h in hurt)
                {
                    var gap = PointSeg(x, h.A, h.B) - h.Radius - 0.05;
                    if (gap <= 0 && (best is null || gap < best.Value.Gap)) best = (gap, h.Name);
                }
            }
            if (best is { } hit) return (t, hit.Name);
        }
        return (double.NaN, "");
    }

    [Fact]
    public void Acceptance_Phase9_HitTest_FirstContactFrameAndBone_MatchAnIndependentOracle()
    {
        var c = C9.Build();
        var s = c.S;
        foreach (var (x, z, facing) in new[] { (0.0, 0.75, 180.0), (-0.3, 0.8, 180.0), (-0.4, 0.6, 90.0) })
        {
            var r = P8.Ok(s, "combat.hit_test", new
            {
                attackerCharacterId = c.Attacker, attackClipId = c.Attack, defenderCharacterId = c.Defender, defenderX = x, defenderZ = z, defenderFacing = facing,
                maxSubsteps = 16,
            }).Data!;
            var (time, bone) = Oracle(c, new Vec3(x, 0, z), facing);
            Assert.False(double.IsNaN(time), $"oracle finds no contact at ({x}, {z})");
            Assert.True((bool)r["hit"]!, $"({x}, {z}): {r.ToJsonString()}");
            var first = r["firstHit"]!;
            var t = (double)first["time"]!;
            // The contact time is refined by bisection on the animation: it matches the oracle's 1/128-frame scan.
            Assert.InRange(t, time - 1.0 / 64, time + 1.0 / 64);
            Assert.Equal((long)Math.Ceiling(t - 1e-9), (long)first["frame"]!);
            Assert.InRange((long)first["frame"]!, 10, 17); // inside the active frames
            Assert.Equal(bone, (string)first["bone"]!);
            Assert.Equal("Blade", (string)first["hitbox"]!);
            // The reaction arguments carry the hit in the defender's frame.
            var ra = r["reactionArgs"]!;
            Assert.Equal(c.Defender, (string)ra["characterId"]!);
            Assert.Equal(1, Math.Sqrt(Math.Pow((double)ra["directionX"]!, 2) + Math.Pow((double)ra["directionZ"]!, 2)), 5);
        }

        // Out of reach: no hit. Outside the active frames: no hit even when overlapping.
        var miss = P8.Ok(s, "combat.hit_test", new { attackerCharacterId = c.Attacker, attackClipId = c.Attack, defenderCharacterId = c.Defender, defenderZ = 3.0 }).Data!;
        Assert.False((bool)miss["hit"]!);
        var early = P8.Ok(s, "combat.hit_test", new { attackerCharacterId = c.Attacker, attackClipId = c.Attack, defenderCharacterId = c.Defender, defenderZ = 0.75, endFrame = 9 }).Data!;
        Assert.False((bool)early["hit"]!);
    }

