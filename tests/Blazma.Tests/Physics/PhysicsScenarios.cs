using System.Text.Json;
using System.Text.Json.Nodes;
using Blazma.AI;
using Blazma.Commands;
using Blazma.Core.Ids;
using Blazma.Core.Model;
using Blazma.Core.Persistence;
using Blazma.Rigging;

namespace Blazma.Tests.Physics;

/// <summary>Clips the physics polish is measured on: the saved Kimodo hero clip, procedural actions, a planned multi-step clip and a
/// baked walk → run sequence blend.</summary>
static class PhysicsScenarios
{
    public static readonly Rig Mannequin = MannequinFactory.Create();

    static string RepoFile(params string[] parts) =>
        Path.Combine(new[] { AppContext.BaseDirectory, "..", "..", "..", "..", ".." }.Concat(parts).ToArray());

    /// <summary>The hero project's clip (look back → run → fall/die, generated by Kimodo) and its rig.</summary>
    public static (Clip Clip, Rig Rig) Hero()
    {
        var p = ProjectFile.Load(RepoFile("marketing", "projects", "hero.blazanim"));
        var clip = p.Clips.OrderByDescending(c => c.DurationFrames).First();
        var ch = p.Characters.First(c => p.FindRig(c.Rig) is not null);
        return (clip, p.FindRig(ch.Rig)!);
    }

    /// <summary>A procedural action retargeted to a mannequin (feet cleaned, no key reduction, not polished).</summary>
    public static Clip Procedural(string prompt, double seconds, ulong seed = 1, Rig? rig = null)
    {
        var motion = new ProceduralMotionProvider().GenerateAsync(new MotionRequest(prompt, seconds, 30, seed), null, CancellationToken.None).GetAwaiter().GetResult();
        return MotionRetargeter.Retarget(motion, rig ?? Mannequin, new RetargetOptions { ReduceKeys = false, Name = prompt }).Clip;
    }

    static CommandRegistry NewRegistry() =>
        CommandRegistry.CreateDefault(new MotionJobService(new IMotionGenerationProvider[] { new ProceduralMotionProvider() }) { AllowBlockingWait = true });

    public static CommandResult Ok(CommandRegistry reg, ProjectSession s, string id, object args)
    {
        CommandResult r;
        try { r = s.Execute(reg.Create(id, JsonNode.Parse(JsonSerializer.Serialize(args))!.AsObject()), CommandOrigin.Test); }
        catch (CommandException e) { r = CommandResult.Fail(e.Code, e.Message); }
        Assert.True(r.Ok, $"{id}: {r.Error?.Code} {r.Error?.Message}");
        return r;
    }

    /// <summary>A planned multi-step generation through motion.generate (procedural provider) on the mannequin.</summary>
    public static (Clip Clip, Rig Rig) Planned(string prompt, double seconds, bool polish, ulong seed = 3)
    {
        var reg = NewRegistry();
        var p = Project.CreateNew("Plan");
        var ch = MannequinFactory.AddTo(p);
        var s = new ProjectSession(p);
        var start = Ok(reg, s, "motion.generate", new { characterId = ch.Id.ToString(), prompt, durationSeconds = seconds, provider = "procedural", seed, physicsPolish = polish }).Data!;
        var jobId = (string)start["jobId"]!;
        for (var i = 0; i < 10 && (string?)Ok(reg, s, "motion.job_status", new { jobId, waitSeconds = 25 }).Data!["state"] == "running"; i++) { }
        var clipId = (string)Ok(reg, s, "motion.job_apply", new { jobId }).Data!["clipId"]!;
        return (p.Clips.Single(c => c.Id == ObjectId.Parse(clipId)), p.FindRig(ch.Rig)!);
    }

    /// <summary>Walk (2 loops) → run (2 loops) as a sequence with a 10-frame blend, baked to a clip.</summary>
    public static (Clip Clip, Rig Rig) SequenceBlend()
    {
        var reg = CommandRegistry.CreateDefault();
        var p = Project.CreateNew("Seq");
        var ch = MannequinFactory.AddTo(p);
        var s = new ProjectSession(p);
        string Template(string id) => (string)Ok(reg, s, "template.apply", new { templateId = id, characterId = ch.Id.ToString(), physicsPolish = false }).Data!["clipId"]!;
        var walk = Template("builtin.walk_cycle");
        var run = Template("builtin.run_cycle");
        var seq = (string)Ok(reg, s, "sequence.create", new { characterId = ch.Id.ToString(), name = "Walk to run" }).Data!["sequenceId"]!;
        Ok(reg, s, "sequence.add_clip", new { sequenceId = seq, clipId = walk, loops = 2 });
        Ok(reg, s, "sequence.add_clip", new { sequenceId = seq, clipId = run, loops = 2, blendFrames = 10, matchFootPhase = true });
        var baked = (string)Ok(reg, s, "sequence.bake", new { sequenceId = seq }).Data!["clipId"]!;
        return (p.Clips.Single(c => c.Id == ObjectId.Parse(baked)), p.FindRig(ch.Rig)!);
    }
}
